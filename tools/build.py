#!/usr/bin/env python3
"""Build Nexus packages (.nxs) from packages/<name>/.

Each package's "description" (at most 80 characters) is checked, and fills
the "{{description}}" placeholder in its registry line.

    python tools/build.py            -> every package into dist/
    python tools/build.py self coffers
"""
import glob, hashlib, json, os, sys

def resolve(node, folder):
    if isinstance(node, dict):
        return {k: resolve(v, folder) for k, v in node.items()}
    if isinstance(node, list):
        return [resolve(v, folder) for v in node]
    if isinstance(node, str) and node.startswith("@file:"):
        return open(os.path.join(folder, node[6:]), encoding="utf-8").read()
    if isinstance(node, str) and node.startswith("@cat:"):
        # "@cat:head.js classes/*.js": the files joined in the order given,
        # each pattern's matches sorted by name. Used for data split one file
        # per class, which Nexus still receives as one function.
        parts = []
        for pattern in node[5:].split():
            matches = sorted(glob.glob(os.path.join(folder, pattern)))
            if not matches:
                sys.exit("%s: %s matches no file" % (folder, pattern))
            parts += [open(m, encoding="utf-8").read() for m in matches]
        return "\n".join(parts)
    return node

MAX_DESCRIPTION = 80
PLACEHOLDER = '"{{description}}"'

def fill(node, value):
    """Put the package's description, as a JS string, where the code has the
    "{{description}}" placeholder (the registry line), so it is written once."""
    if isinstance(node, dict):
        return {k: fill(v, value) for k, v in node.items()}
    if isinstance(node, list):
        return [fill(v, value) for v in node]
    if isinstance(node, str):
        return node.replace(PLACEHOLDER, value)
    return node

# ---- Hot scripts (#136) ------------------------------------------------
# Nexus runs every script through exec_script, which builds a prelude
# declaring each API function and compiles prelude + script with new
# Function on every single call, with no cache. A script's cost grows with
# its length, comments included (measured: ~0.09 ms + 0.06 ms per 1,000
# characters). So in the built package each sizeable script becomes a short
# stub, and its body a plain function made once per load by the generated
# function <pkg>__hot. Bodies made inside a script keep every API name in
# scope. The stub carries a stamp of the bodies, so a reimported package
# rebuilds them instead of running the old ones. tools/extract.py undoes this.
HOT_MIN = 600            # shorter scripts cost about what a stub does
HOT_SKIP = {"onInstall", "onLoad", "onUninstall"}  # run once; keep them plain
HOT_TAG = "/*loom-hot "

def hot(d, folder_name):
    pkg = d.get("name") or folder_name
    bodies = []          # (key, code)
    targets = []         # (holder dict, field, key)
    n = [0]

    def walk(items):
        for it in items or []:
            if it.get("type") == "function" and isinstance(it.get("code"), str):
                if it.get("name") not in HOT_SKIP and len(it["code"]) >= HOT_MIN:
                    key = "f:" + it["name"]
                    bodies.append((key, it["code"]))
                    targets.append((it, "code", key))
            for a in it.get("actions") or []:
                if isinstance(a.get("script"), str):
                    n[0] += 1
                    if len(a["script"]) >= HOT_MIN:
                        key = "s:%d" % n[0]
                        bodies.append((key, a["script"]))
                        targets.append((a, "script", key))
            if it.get("items"):
                walk(it["items"])

    walk(d.get("items"))
    if not bodies:
        return d
    stamp = hashlib.sha1(json.dumps(bodies, ensure_ascii=False).encode("utf-8")).hexdigest()[:10]
    P = json.dumps(pkg, ensure_ascii=False)
    for holder, field, key in targets:
        K = json.dumps(key)
        holder[field] = (
            '%s%s %s %s*/var lhH = client.loom && client.loom.__hot && client.loom.__hot[%s];\n'
            'if (!lhH || lhH.v !== "%s") { run_function(%s, [], %s); lhH = client.loom.__hot[%s]; }\n'
            'lhH.f[%s](args);'
        ) % (HOT_TAG, folder_name, key, stamp, P, stamp, json.dumps(folder_name + "__hot"), P, P, K)
    out = [
        "// %s__hot -- generated by tools/build.py (#136). The bodies of this package's" % folder_name,
        "// longer scripts, made once per load; each script in the package is a stub",
        "// that calls its body here. Edit the source in packages/%s/, never this." % folder_name,
        "if (!client.loom) client.loom = {};",
        "if (!client.loom.__hot) client.loom.__hot = {};",
        "var lhP = client.loom.__hot[%s] = { v: \"%s\", f: {} };" % (P, stamp),
    ]
    for key, code in bodies:
        out.append("lhP.f[%s] = function (args) {" % json.dumps(key))
        out.append("//@hot-begin " + key)
        out.append(code)
        out.append("//@hot-end " + key)
        out.append("};")
    d.setdefault("items", []).append({"type": "function", "name": folder_name + "__hot", "enabled": True, "code": "\n".join(out) + "\n"})
    return d

def build(name, root="packages", dist="dist"):
    folder = os.path.join(root, name)
    d = resolve(json.load(open(os.path.join(folder, "package.json"), encoding="utf-8")), folder)
    # The description is what Nexus shows on its packages page and what LOOM
    # shows under the package: required, one line, at most 80 characters.
    desc = d.get("description", "")
    if not desc or "\n" in desc or len(desc) > MAX_DESCRIPTION:
        sys.exit("%s: the description must be one line of 1-%d characters (it is %d)" % (name, MAX_DESCRIPTION, len(desc)))
    d = fill(d, json.dumps(desc, ensure_ascii=False))
    d = hot(d, name)
    os.makedirs(dist, exist_ok=True)
    path = os.path.join(dist, name + ".nxs")
    json.dump(d, open(path, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print("built", path)

if __name__ == "__main__":
    names = sys.argv[1:] or sorted(n for n in os.listdir("packages") if os.path.isfile(os.path.join("packages", n, "package.json")))
    for n in names:
        build(n)
