if (client.hl && client.hl.enemies[vinesTarget.toLowerCase()]) {
  if (eleusisLocations.includes(vinesLocation)) {

    // record last-known location (always, even if reporting is off)
    var enemyLocations = {};
    var stored = get_variable("enemyLocations");
    if (stored) { try { enemyLocations = JSON.parse(stored); } catch (e) {} }

    enemyLocations[vinesTarget.toLowerCase()] = {
      name: vinesTarget,          // keep original casing for display
      location: vinesLocation,
      time: Date.now()
    };
    set_variable("enemyLocations", JSON.stringify(enemyLocations));

    // broadcast only if reporting is on
    if (reportEnemies == 1) {
      send_command("pt ENEMY ALERT: " + vinesTarget + " is in Eleusis, at " + vinesLocation);
    }
  }
}